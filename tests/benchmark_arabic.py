"""Measure Arabic PDF->text accuracy of Waraq against common extractors.

    python tests/benchmark_arabic.py      (writes docs/benchmark.md)

Metric: per-line exact match against the source text, the same ignoring
harakat (tashkeel), and character error rate (CER, edit distance / length)
over the whole page.  Lower CER is better.
"""
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from waraq.core import arabic  # noqa: E402
from waraq.core.extract import extract_pages, save_docx, docx_paragraph_texts  # noqa: E402

FIX = ROOT / "tests" / "_fixtures"
DATA = ROOT / "tests" / "data"
HARAKAT = {chr(c) for c in range(0x064B, 0x0653)} | {"\u0670"}


def strip_h(s):
    return "".join(c for c in s if c not in HARAKAT)


def src(name):
    return [l for l in (DATA / name).read_text(encoding="utf-8").splitlines() if l.strip()]


def clean(lines):
    return [arabic.squash_ws(l) for l in lines if l.strip() and not l.strip().startswith("page ")]


def waraq_docx(pdf, layout):
    out = Path("/tmp") / (pdf.stem + f"-{layout}.docx")
    save_docx(extract_pages(pdf, pages=[0]), out, layout=layout)
    return clean(docx_paragraph_texts(out))


def pypdf_lines(pdf):
    from pypdf import PdfReader
    return clean(PdfReader(str(pdf)).pages[0].extract_text() or "".splitlines())


def pdfminer_lines(pdf):
    from pdfminer.high_level import extract_text
    return clean(extract_text(str(pdf), page_numbers=[0]).splitlines())


def pdftotext_lines(pdf):
    if not shutil.which("pdftotext"):
        return None
    r = subprocess.run(["pdftotext", "-l", "1", "-layout", "-enc", "UTF-8", str(pdf), "-"], capture_output=True, text=True)
    return clean(r.stdout.splitlines())


def score(ref, got):
    exact = sum(1 for r in ref if r in got)
    loose_got = {strip_h(g) for g in got}
    loose = sum(1 for r in ref if strip_h(r) in loose_got)
    cer = arabic.char_error_rate("\n".join(ref), "\n".join(got))
    return exact, loose, cer


CASES = [
    ("arabic_reportlab.pdf", "arabic_lines.txt", "lines", "ReportLab (python-bidi visual order, presentation forms)"),
    ("arabic_writer.pdf", "arabic_lines.txt", "lines", "LibreOffice Writer, Amiri font (HarfBuzz)"),
    ("arabic_writer_dejavu.pdf", "arabic_lines.txt", "lines", "LibreOffice Writer, DejaVu Sans"),
    ("arabic_paragraphs.pdf", "arabic_paragraphs.txt", "paragraphs", "LibreOffice Writer, justified Amiri paragraphs"),
]


def main():
    rows = []
    for pdf, ref_name, layout, desc in CASES:
        p = FIX / pdf
        if not p.exists():
            continue
        ref = clean(src(ref_name))
        tools = {"Waraq (docx)": waraq_docx(p, layout), "pypdf": pypdf_lines(p), "pdfminer.six": pdfminer_lines(p),
                 "pdftotext": pdftotext_lines(p)}
        for tool, got in tools.items():
            if got is None:
                continue
            if layout == "paragraphs" and tool != "Waraq (docx)":
                got = [" ".join(got)]
                ref_cmp = [" ".join(ref)]
            else:
                ref_cmp = ref
            e, l, c = score(ref_cmp, got)
            rows.append((pdf, desc, tool, f"{e}/{len(ref_cmp)}", f"{l}/{len(ref_cmp)}", f"{c:.3f}"))
    md = ["| PDF | producer | tool | exact lines | ignoring harakat | CER |", "|---|---|---|---|---|---|"]
    md += ["| " + " | ".join(r) + " |" for r in rows]
    text = "\n".join(md)
    print(text)
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "benchmark.md").write_text(
        "# Arabic PDF → text benchmark\n\nGenerated by `tests/benchmark_arabic.py`. Only page 1 of each fixture is compared. Fixtures are made by "
        "`tests/make_fixtures.py` from the text in `tests/data`. CER = character error rate "
        "(0 = perfect).\n\n" + text + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
